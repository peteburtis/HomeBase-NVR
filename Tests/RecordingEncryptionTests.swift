import XCTest
import Foundation
import CryptoKit
import Darwin

final class RecordingEncryptionTests: XCTestCase {
    private let password = "test-only passphrase: café 🔐"
    private var roots: [String] = []
    override func tearDownWithError() throws { for path in roots { try FileManager.default.removeItem(atPath: path) }; roots.removeAll() }
    private func root() throws -> String {
        let path = "/private/tmp/hbnvr-encryption-" + UUID().uuidString
        try SecureFiles.ensureDirectory(path, owner: geteuid(), mode: 0o700); roots.append(path); return path
    }
    func testSystemPBKDF2MatchesSHA256KnownAnswer() throws {
        let key = try RecordingEncryption.deriveKey(password: "password", salt: Data("salt".utf8), rounds: 1)
        XCTAssertEqual(key.withUnsafeBytes { $0.map { String(format: "%02x", $0) }.joined() },
                       "120fb6cffcf8b32c43e7225256c4f837a86548c92ccc35480805987cb70be17b")
    }
    func testEnvelopeRoundTripAndRandomization() throws {
        for bytes in [Data(), Data((0...255).map(UInt8.init))] {
            let one = try RecordingEncryption.encrypt(bytes, password: password)
            let two = try RecordingEncryption.encrypt(bytes, password: password)
            XCTAssertNotEqual(one, two)
            XCTAssertEqual(one.count, bytes.count + 72)
            XCTAssertEqual(one.prefix(8), Data("HBNVRE01".utf8))
            XCTAssertEqual(Array(one[8..<12]), [0, 9, 39, 192])
            XCTAssertEqual(try RecordingEncryption.decrypt(one, password: password), bytes)
            XCTAssertEqual(try RecordingEncryption.decrypt(two, password: password), bytes)
        }
    }
    func testDecryptsIndependentOpenSSLEnvelope() throws {
        // Generated by Node crypto (OpenSSL), not the implementation under test:
        // PBKDF2-SHA256 600000, salt bytes 0...31, nonce bytes 32...43, header AAD.
        let fixture = Data(base64Encoded: "SEJOVlJFMDEACSfAAAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8gISIjJCUmJygpKisoturA7Czgie/kJ6LijBNu0L0hoXq28bZ3U0WDyuMJptqSwL4BlKlsNw9494LK8g==")!
        XCTAssertEqual(try RecordingEncryption.decrypt(fixture, password: "independent test password"), Data("independent synthetic recording".utf8))
    }
    func testWrongPasswordCorruptionTruncationAndUnsupportedKDF() throws {
        let original = try RecordingEncryption.encrypt(Data(repeating: 0xa5, count: 100), password: password)
        XCTAssertThrowsError(try RecordingEncryption.decrypt(original, password: "wrong password"))
        // Version, work factor, salt, nonce, ciphertext and authentication tag.
        for offset in [0, 7, 8, 12, 44, 56, original.count - 1] {
            var damaged = original; damaged[offset] ^= 1
            XCTAssertThrowsError(try RecordingEncryption.decrypt(damaged, password: password))
        }
        for count in [0, 8, 55, 71, 72, original.count - 1] {
            XCTAssertThrowsError(try RecordingEncryption.decrypt(Data(original.prefix(count)), password: password))
        }
        var extra = original; extra.append(0)
        XCTAssertThrowsError(try RecordingEncryption.decrypt(extra, password: password))
    }
    func testPasswordIsExactUTF8AndValidatedWithoutNormalization() throws {
        let envelope = try RecordingEncryption.encrypt(Data([1, 2, 3]), password: " spaces matter ")
        XCTAssertThrowsError(try RecordingEncryption.decrypt(envelope, password: "spaces matter"))
        XCTAssertEqual(try RecordingEncryption.decrypt(envelope, password: " spaces matter "), Data([1, 2, 3]))
        for invalid in ["", "a\0b", "a\nb", "a\rb", String(repeating: "é", count: 513)] {
            XCTAssertThrowsError(try RecordingEncryption.validatePassword(invalid))
        }
        XCTAssertNoThrow(try RecordingEncryption.validatePassword(String(repeating: "é", count: 512)))
        // Swift String equality considers these equivalent, but the KDF uses exact bytes.
        let composed = "caf\u{e9}", decomposed = "cafe\u{301}"
        XCTAssertNotEqual(S3ClientEncryption(password: composed), S3ClientEncryption(password: decomposed))
        let unicode = try RecordingEncryption.encrypt(Data([42]), password: composed)
        XCTAssertThrowsError(try RecordingEncryption.decrypt(unicode, password: decomposed))
    }
    func testPrivateConfigurationRedactionPreservationReplacementAndOptOut() throws {
        var c = try S3Tests().config()
        c.s3?.clientEncryption = S3ClientEncryption(password: password)
        XCTAssertThrowsError(try c.validate()) // Version-1 readers would ignore encryption.
        c.schemaVersion = 2
        XCTAssertNoThrow(try c.validate())
        let privateJSON = try CameraJSON.encode(c)
        XCTAssertEqual(try JSONDecoder().decode(RecordingStoreConfiguration.self, from: privateJSON), c)
        let publicJSON = try CameraJSON.encode(c.summary)
        XCTAssertFalse(String(decoding: publicJSON, as: UTF8.self).contains("Password"))
        XCTAssertTrue(c.summary.s3?.clientEncryption?.enabled == true)
        var edited = c.summary.s3!
        edited.preservePrivateSettings(from: c.s3!)
        XCTAssertEqual(edited.clientEncryption?.password, password)
        edited.clientEncryption = nil // An older client must not disable encryption.
        edited.preservePrivateSettings(from: c.s3!)
        XCTAssertEqual(edited.clientEncryption?.password, password)
        edited.clientEncryption = S3ClientEncryption(password: "replacement password")
        edited.preservePrivateSettings(from: c.s3!)
        XCTAssertEqual(edited.clientEncryption?.password, "replacement password")
        edited.clientEncryption = S3ClientEncryption(enabled: false)
        edited.preservePrivateSettings(from: c.s3!)
        XCTAssertNil(edited.clientEncryption?.password); XCTAssertFalse(edited.clientEncryption!.enabled)
        XCTAssertNoThrow(try edited.validate(requireCredentials: true))
        XCTAssertThrowsError(try S3ClientEncryption(password: nil).validate(requirePassword: true))
        XCTAssertThrowsError(try S3ClientEncryption(enabled: false, password: password).validate())
        let missing = c.summary
        XCTAssertThrowsError(try missing.s3!.validate(requireCredentials: true))
        let repository = RecordingStoreRepository(directory: try root() + "/stores")
        XCTAssertThrowsError(try repository.save(missing, replacing: false))
        try repository.save(c, replacing: false)
        XCTAssertEqual(try repository.list().first?.s3?.clientEncryption?.password, password)
    }
    func testEncryptedSpoolIsSelfContainedAndOldPlaintextSpoolsStillReplay() throws {
        let c = try S3Tests().config(), path = try root() + "/" + c.id
        let spool = try S3Spool(path: path, storeID: c.id, settings: c.s3!.settings)
        let plaintext = Data("synthetic private video".utf8)
        let encrypted = try RecordingEncryption.encrypt(plaintext, password: password)
        let m = S3ShardMetadata.make(store: c, camera: UUID().uuidString, name: "Camera", capturedAt: Date(), data: encrypted, encrypted: true)
        let entry = try spool.publish(m, data: encrypted)
        XCTAssertEqual(m.contentType, "application/octet-stream"); XCTAssertTrue(m.key.hasSuffix(".mp4.hbnvr"))
        XCTAssertTrue(FileManager.default.fileExists(atPath: entry.directory + "/video.mp4.hbnvr"))
        XCTAssertFalse(FileManager.default.fileExists(atPath: entry.directory + "/video.mp4"))
        XCTAssertFalse(String(decoding: try Data(contentsOf: URL(fileURLWithPath: entry.directory + "/metadata.json")), as: UTF8.self).contains(password))
        let legacy = S3ShardMetadata.make(store: c, camera: UUID().uuidString, name: "Old", capturedAt: Date(), data: plaintext)
        _ = try spool.publish(legacy, data: plaintext)
        let recovered = try S3Spool(path: path, storeID: c.id, settings: c.s3!.settings)
        XCTAssertTrue(recovered.damaged.isEmpty); XCTAssertEqual(recovered.entries.count, 2)
        let bytes = try XCTUnwrap(recovered.entries[m.id]).payload.read(offset: 0, count: encrypted.count)
        XCTAssertEqual(bytes, encrypted)
        XCTAssertEqual(try RecordingEncryption.decrypt(bytes, password: password), plaintext)
        XCTAssertEqual(try recovered.entries[legacy.id]?.payload.read(offset: 0, count: plaintext.count), plaintext)
        try recovered.delivered(m.id); XCTAssertNil(recovered.entries[m.id]); XCTAssertNotNil(recovered.entries[legacy.id])
    }
    func testOfflineDecryptAuthenticatesBeforeOutputAndNeverOverwrites() throws {
        let path = try root(), input = path + "/input.mp4.hbnvr", output = path + "/output.mp4"
        let plaintext = Data("synthetic recording".utf8)
        try SecureFiles.atomicWrite(RecordingEncryption.encrypt(plaintext, password: password), to: input, mode: 0o600)
        XCTAssertThrowsError(try RecordingEncryption.decryptFile(input: input, output: output, password: "incorrect"))
        XCTAssertFalse(FileManager.default.fileExists(atPath: output))
        try RecordingEncryption.decryptFile(input: input, output: output, password: password)
        XCTAssertEqual(try Data(contentsOf: URL(fileURLWithPath: output)), plaintext)
        XCTAssertEqual(try SecureFiles.info(output)!.st_mode & 0o777, 0o600)
        XCTAssertThrowsError(try RecordingEncryption.decryptFile(input: input, output: output, password: password))
        XCTAssertEqual(try Data(contentsOf: URL(fileURLWithPath: output)), plaintext)
        let link = path + "/link.mp4"
        XCTAssertEqual(symlink(output, link), 0)
        XCTAssertThrowsError(try RecordingEncryption.decryptFile(input: input, output: link, password: password))
        XCTAssertFalse(try FileManager.default.contentsOfDirectory(atPath: path).contains { $0.hasPrefix(".hbnvr-decrypt-") })
    }
}
